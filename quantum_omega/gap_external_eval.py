"""Evaluate a frozen TGA ranking against externally supplied pairwise judgments.

No labels are shipped or generated by this module. Callers must preserve their
provenance, preregistration, and independence records outside the score.
"""
import json
from hashlib import sha256

def evaluate_labels(report, judgments):
    if not isinstance(report, dict) or report.get("kind") != "review_priority_heuristic":
        raise ValueError("Expected a frozen TGA priority report")
    rows = report.get("ranked_claims")
    if not isinstance(rows, list) or not all(isinstance(r, dict) and isinstance(r.get("claim_id"), str) for r in rows):
        raise ValueError("Invalid ranked claims")
    ids = [r["claim_id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate ranked claims")
    if not isinstance(judgments, dict) or set(judgments) != {"schema_version", "source_id", "pairs"} or judgments["schema_version"] != 1:
        raise ValueError("Invalid label schema")
    source = judgments["source_id"]
    if not isinstance(source, str) or not source.strip():
        raise ValueError("A label provenance source_id is required")
    pairs = judgments["pairs"]
    if not isinstance(pairs, list) or not pairs:
        raise ValueError("At least one pairwise judgment is required")
    positions = {name: i for i, name in enumerate(ids)}
    seen = set()
    normalized = []
    for pair in pairs:
        if not isinstance(pair, dict) or set(pair) != {"higher_priority", "lower_priority"}:
            raise ValueError("Invalid pairwise judgment")
        higher, lower = pair["higher_priority"], pair["lower_priority"]
        if not isinstance(higher, str) or not isinstance(lower, str) or higher == lower or higher not in positions or lower not in positions:
            raise ValueError("Unknown or identical claim identifiers")
        key = tuple(sorted((higher, lower)))
        if key in seen:
            raise ValueError("Duplicate or conflicting pairwise judgment")
        seen.add(key)
        normalized.append((higher, lower))
    def score(order):
        rank = {name: i for i, name in enumerate(order)}
        return sum(rank[a] < rank[b] for a, b in normalized) / len(normalized)
    baseline = sorted(ids)
    # Compare against an intentionally simple no-feature baseline.
    result = {
        "schema_version": 1,
        "evaluation_type": "externally_supplied_pairwise_labels",
        "label_source_id": source,
        "label_count": len(normalized),
        "ranked_claim_count": len(ids),
        "priority_report_sha256": report.get("sha256"),
        "metric": "pairwise_order_accuracy",
        "scores": {
            "tga_heuristic": score(ids),
            "alphabetical_baseline": score(baseline),
        },
        "independence_verified": False,
        "scientific_calibration": False,
        "note": "Caller-provided labels are not automatically independent, blinded, or expert-reviewed.",
    }
    result["sha256"] = sha256(json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()
    return result
